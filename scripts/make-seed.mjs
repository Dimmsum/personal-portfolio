// Turns the Markdown files in content/posts and content/projects into supabase/seed.sql.
// Run: node scripts/make-seed.mjs   (then paste seed.sql into the Supabase SQL editor)
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (folder) =>
  fs
    .readdirSync(path.join(root, "content", folder))
    .filter((f) => f.endsWith(".md") && !f.startsWith("_"))
    .map((f) => ({ slug: f.replace(/\.md$/, ""), ...matter(fs.readFileSync(path.join(root, "content", folder, f), "utf8")) }));

const str = (v) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const arr = (v) => `array[${(v ?? []).map(str).join(",")}]::text[]`;
const date = (d) => (d instanceof Date ? d.toISOString().slice(0, 10) : String(d));

const posts = read("posts").map(
  ({ slug, data, content }) =>
    `(${[str(slug), str(data.title ?? slug), str(date(data.date)), str(data.tag ?? "Notes"), str(data.excerpt), str(content.trim()), "true"].join(", ")})`,
);
const projects = read("projects").map(
  ({ slug, data, content }) =>
    `(${[
      str(slug),
      str(data.title ?? slug),
      Number(data.year ?? new Date().getFullYear()),
      str(data.type ?? "Other"),
      str(data.status),
      Boolean(data.featured),
      Number(data.order ?? 99),
      arr(data.tags),
      str(data.blurb),
      arr(data.images),
      str(data.link),
      str(data.repo),
      str(content.trim()),
      "true",
    ].join(", ")})`,
);

const sql = `-- Generated by scripts/make-seed.mjs from content/. Safe to run more than once.
insert into public.posts (slug, title, date, tag, excerpt, body, published) values
${posts.join(",\n")}
on conflict (slug) do nothing;

insert into public.projects (slug, title, year, type, status, featured, sort_order, tags, blurb, images, link, repo, body, published) values
${projects.join(",\n")}
on conflict (slug) do nothing;
`;
fs.writeFileSync(path.join(root, "supabase", "seed.sql"), sql);
console.log(`Wrote supabase/seed.sql: ${posts.length} posts, ${projects.length} projects`);
